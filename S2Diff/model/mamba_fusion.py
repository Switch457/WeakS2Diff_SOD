    def forward(self, x1: torch.Tensor, x2: torch.Tensor, **kwargs):
        assert x1.shape == x2.shape, " SS2D fuse 2 features with the same shape! "
        B, H, W, C = x1.shape

        xz1 = self.in_proj1(x1)
        x1, z1 = xz1.chunk(2, dim=-1)
        x1 = x1.permute(0, 3, 1, 2).contiguous()
        x1 = self.act1(self.conv2d1(x1)) 

        xz2 = self.in_proj2(x2) # (b, h, w, d)
        x2, z2 = xz2.chunk(2, dim=-1)
        x2 = x2.permute(0, 3, 1, 2).contiguous()
        x2 = self.act2(self.conv2d2(x2)) # (b, d, h, w)
        y1, y2 = self.forward_core(x1, x2)

        y1 = y1 * F.silu(z1)
        y2 = y2 * F.silu(z2)
        out = self.out_proj(y1 + y2)
        if self.dropout is not None:
            out = self.dropout(out)
        return out

    
